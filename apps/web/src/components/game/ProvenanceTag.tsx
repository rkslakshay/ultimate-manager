import type { Provenance } from '@um/engine';
import { cn } from '@/lib/utils';

const LABELS: Record<Provenance, { text: string; title: string; tone: string }> = {
  source_backed: {
    text: 'source',
    title: 'From the imported real-world data',
    tone: 'text-success',
  },
  derived: {
    text: 'derived',
    title: 'Not in the source data: derived by the game from related data',
    tone: 'text-warning',
  },
  simulated: {
    text: 'simulated',
    title: 'Not in the source data: generated by the simulation',
    tone: 'text-warning',
  },
  unverified: {
    text: 'unverified',
    title: 'From a source but not verified',
    tone: 'text-fg-subtle',
  },
  unknown: { text: 'unknown', title: 'Not available in the data', tone: 'text-fg-subtle' },
};

/**
 * Small inline marker for values that are NOT plain source data (derived, simulated, unknown…).
 * Source-backed values carry no tag: the player's "Real player" badge covers them.
 */
export function ProvenanceTag({
  status,
  className,
}: {
  status: Provenance | undefined;
  className?: string;
}) {
  if (!status || status === 'source_backed') return null;
  const l = LABELS[status];
  return (
    <span
      title={l.title}
      className={cn(
        'ml-1.5 rounded-sm border border-current/30 px-1 text-[10px] font-medium uppercase tracking-wide',
        l.tone,
        className,
      )}
    >
      {l.text}
    </span>
  );
}
